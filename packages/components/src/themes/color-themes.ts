/** The color theme with the given id, or undefined when the id is null or no longer in the catalog. */
export function findColorTheme(id: string | null): ColorTheme | undefined {
  if (id === null) {
    return undefined;
  }

  return COLOR_THEMES.find((colorTheme) => colorTheme.id === id);
}
